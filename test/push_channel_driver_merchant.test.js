const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const file = fs.readFileSync(path.join(__dirname, '..', 'src', 'notification_service.js'), 'utf8');
const prefix = file.slice(0, file.indexOf('function createNotificationService('));
const ctx = { require, console };
vm.runInNewContext(prefix, ctx);
const f = ctx.notificationAndroidChannel;
assert.equal(f({ targetType: 'DRIVER', type: 'BOOKING_OFFER' }).id, 'imove_driver_orders_v1');
assert.equal(f({ targetType: 'DRIVER', type: 'COMMERCE_ORDER' }).sound, 'imove_new_order');
assert.equal(f({ targetType: 'MERCHANT', type: 'MERCHANT_ORDER_NEW' }).id, 'imove_merchant_orders_v1');
assert.equal(f({ targetType: 'CUSTOMER', type: 'COMMERCE_ORDER' }).id, 'imove_user_heads_up_v2');
assert.equal(f({ targetType: 'MERCHANT', type: 'ADMIN_BROADCAST' }).id, 'imove_general_v2');
assert.equal(f({ targetType: 'DRIVER', type: 'ADMIN_BROADCAST', level: 1 }).id, 'imove_critical_v2');
const data = ctx.notificationFcmData({ orderId: 15, closed: false, s: 'ok', empty: null });
assert.equal(data.orderId, '15');
assert.equal(data.closed, 'false');
assert.equal(data.s, 'ok');
assert.equal(data.empty, '');
console.log('PASS: 10 checks notification channel, sound, FCM data');

'use strict';
const fs=require('fs'),assert=require('assert'),vm=require('vm'),path=require('path');
const root=path.join(process.cwd(),'src');
const policy=fs.readFileSync(path.join(root,'matching_policy.js'),'utf8');
const engine=fs.readFileSync(path.join(root,'matching_engine.js'),'utf8');
const start=policy.indexOf('function normalizeScoreParts(');
const end=policy.indexOf('async function rankMatchingCandidates(',start);
assert(start>=0&&end>start,'Cannot locate score function');
const calculate=vm.runInNewContext(policy.slice(start,end)+'\nnormalizeScoreParts;',{});
const p={maxRadiusKm:10,fairness:{idleCapMinutes:360}};
const maxima={maxRecentTrips:1,maxPoints:0};
const nullScore=calculate({distanceKm:null,driver:{}},p,maxima);
const gpsScore=calculate({distanceKm:2,driver:{}},p,maxima);
assert.equal(nullScore.distance,0,'No GPS must score 0');
assert.equal(calculate({driver:{}},p,maxima).distance,0,'Missing GPS must score 0');
assert.equal(gpsScore.distance,80,'GPS 2km/10km must score 80');
assert.equal(calculate({distanceKm:0,driver:{}},p,maxima).distance,100,'Real zero-distance GPS remains valid');
const sortStart=policy.indexOf('  }).sort((a, b) => {',end);
const sortEnd=policy.indexOf('  }).map((candidate, index)',sortStart);
assert(sortStart>=0&&sortEnd>sortStart,'Missing comparator');
const sortBody=policy.slice(sortStart+'  }).sort((a, b) => '.length,sortEnd+3);
const compare=vm.runInNewContext('(function(a,b) '+sortBody+')');
const gps={distanceKm:2,matchingScore:25,driver:{rating:3}};
const noGps={distanceKm:null,matchingScore:95,driver:{rating:5}};
assert(compare(gps,noGps)<0,'Valid GPS should outrank missing GPS');
assert(compare(noGps,gps)>0,'Missing GPS should fall after valid GPS');
assert(engine.includes('{ approvedServiceCodes: code }'),'Vehicle lookup must honor approved service codes');
assert(engine.includes('distanceKm: candidate.distanceKm != null && Number.isFinite(Number(candidate.distanceKm))'), 'V6.9 preview must preserve absent GPS distance');
console.log('PASS 8 checks — null GPS scoring, measured GPS, GPS priority both directions, KYC service lookup');
